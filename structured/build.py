"""Build data/structured/property_facts.db: exact, queryable property facts (no embeddings).

Sources: data/synthetic/*.csv (generated by `python -m synthetic.generate`).

Tables   companies, properties, unit_types, fees, pet_policies, parking, utilities, amenities, units, leases
Views    v_current_fees      fees in effect today (effective_from <= today, effective_to empty or >= today)
         v_monthly_costs     advertised rent range + required monthly charges, per unit type
         v_move_in_costs     first month + deposit + required one-time charges, per unit type
         v_pet_costs         one-time and monthly pet charges for one pet, with the pet rules

Usage:   python -m structured.build
"""
from __future__ import annotations

import csv
import sqlite3
from datetime import datetime, timezone
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SRC = ROOT / "data" / "synthetic"
DB_DIR = ROOT / "data" / "structured"
DB_PATH = DB_DIR / "property_facts.db"

SCHEMA = """
PRAGMA foreign_keys = ON;

CREATE TABLE companies (
    company_id TEXT PRIMARY KEY, name TEXT NOT NULL, ticker TEXT, hq_city TEXT, website TEXT, description TEXT,
    emergency_line TEXT, office_email TEXT, source_urls TEXT, verified_on DATE);

CREATE TABLE properties (
    property_id TEXT PRIMARY KEY, company_id TEXT NOT NULL REFERENCES companies, name TEXT NOT NULL,
    city TEXT, state TEXT, district TEXT, address TEXT, owner TEXT, year_built INTEGER, units INTEGER,
    floors INTEGER, has_elevator INTEGER, heat_controlled_by TEXT, quiet_hours TEXT, office_hours TEXT,
    site_contact TEXT, site_phone TEXT, emergency_line TEXT, rent_regulated INTEGER, verified_on DATE);

CREATE TABLE unit_types (
    property_id TEXT NOT NULL REFERENCES properties, unit_type TEXT NOT NULL, bedrooms INTEGER, bathrooms INTEGER,
    sqft_min INTEGER, sqft_max INTEGER, rent_min INTEGER, rent_max INTEGER, provenance TEXT, source_url TEXT,
    observed_on DATE, PRIMARY KEY (property_id, unit_type), CHECK (rent_min <= rent_max));

CREATE TABLE fees (
    fee_id TEXT PRIMARY KEY, property_id TEXT NOT NULL REFERENCES properties, fee_code TEXT NOT NULL,
    fee_name TEXT NOT NULL,
    category TEXT CHECK (category IN ('application','deposit','recurring','pet','parking','utility','amenity',
                                      'penalty','service')),
    amount REAL NOT NULL CHECK (amount >= 0),
    basis TEXT CHECK (basis IN ('flat','per_pet','months_of_rent')),
    frequency TEXT CHECK (frequency IN ('one_time','monthly','per_occurrence')),
    required INTEGER, refundable INTEGER, provenance TEXT CHECK (provenance IN ('listing','synthetic')),
    notes TEXT, effective_from DATE, effective_to DATE, source_url TEXT, observed_on DATE);
CREATE INDEX fees_property ON fees (property_id, category);

CREATE TABLE pet_policies (
    property_id TEXT PRIMARY KEY REFERENCES properties, cats_allowed INTEGER, dogs_allowed INTEGER,
    max_pets INTEGER, max_weight_lb INTEGER, breed_restrictions TEXT, registration_required INTEGER,
    provenance TEXT, notes TEXT, source_url TEXT, observed_on DATE);

CREATE TABLE parking (
    parking_id TEXT PRIMARY KEY, property_id TEXT NOT NULL REFERENCES properties, parking_type TEXT,
    spaces INTEGER, assigned INTEGER, ev_charging INTEGER, waitlist INTEGER, provenance TEXT, notes TEXT,
    source_url TEXT, observed_on DATE);

CREATE TABLE utilities (
    property_id TEXT NOT NULL REFERENCES properties, utility TEXT NOT NULL,
    responsibility TEXT CHECK (responsibility IN ('included','tenant_direct','billed_back')),
    provider TEXT, provenance TEXT, source_url TEXT, observed_on DATE, PRIMARY KEY (property_id, utility));

CREATE TABLE amenities (
    amenity_id TEXT PRIMARY KEY, property_id TEXT NOT NULL REFERENCES properties, amenity TEXT, category TEXT,
    hours TEXT, reservation_required INTEGER, fee_id TEXT REFERENCES fees, provenance TEXT, source_url TEXT,
    observed_on DATE);

CREATE TABLE units (
    unit_id TEXT PRIMARY KEY, property_id TEXT NOT NULL REFERENCES properties, unit_number TEXT, floor INTEGER,
    unit_type TEXT, bedrooms INTEGER, bathrooms INTEGER, sqft INTEGER, status TEXT);

CREATE TABLE leases (
    lease_id TEXT PRIMARY KEY, unit_id TEXT NOT NULL REFERENCES units, tenant_id TEXT, start_date DATE,
    end_date DATE, monthly_rent INTEGER, security_deposit INTEGER, lease_type TEXT, pet_addendum INTEGER);

CREATE TABLE meta (key TEXT PRIMARY KEY, value TEXT);

-- Views take "today" from the meta table (set at build time; overridable with structured.query.as_of()).
CREATE VIEW v_current_fees AS
SELECT f.* FROM fees f, (SELECT value AS today FROM meta WHERE key = 'as_of') m
WHERE f.effective_from <= m.today AND (f.effective_to IS NULL OR f.effective_to >= m.today);

CREATE VIEW v_monthly_costs AS
SELECT u.property_id, p.name AS property, u.unit_type, u.bedrooms, u.rent_min, u.rent_max,
       COALESCE(SUM(CASE WHEN f.basis = 'flat' THEN f.amount END), 0) AS required_monthly_fees,
       GROUP_CONCAT(CASE WHEN f.basis = 'flat' THEN f.fee_name || ' ' || CAST(f.amount AS INTEGER) END, '; ')
           AS fee_breakdown,
       u.rent_min + COALESCE(SUM(CASE WHEN f.basis = 'flat' THEN f.amount END), 0) AS total_min,
       u.rent_max + COALESCE(SUM(CASE WHEN f.basis = 'flat' THEN f.amount END), 0) AS total_max
FROM unit_types u JOIN properties p USING (property_id)
LEFT JOIN v_current_fees f ON f.property_id = u.property_id AND f.frequency = 'monthly' AND f.required = 1
GROUP BY u.property_id, u.unit_type;

CREATE VIEW v_move_in_costs AS
SELECT u.property_id, p.name AS property, u.unit_type, u.bedrooms,
       u.rent_min AS first_month_min, u.rent_max AS first_month_max,
       COALESCE(MAX(CASE WHEN f.category = 'deposit' AND f.basis = 'months_of_rent' THEN f.amount END), 0)
           AS deposit_months_of_rent,
       COALESCE(SUM(CASE WHEN f.basis = 'flat' AND f.category = 'deposit' AND f.fee_code LIKE 'security%'
                         THEN f.amount END), 0) AS deposit_flat,
       COALESCE(SUM(CASE WHEN f.basis = 'flat' AND NOT (f.category = 'deposit' AND f.fee_code LIKE 'security%')
                         THEN f.amount END), 0) AS other_one_time
FROM unit_types u JOIN properties p USING (property_id)
LEFT JOIN v_current_fees f ON f.property_id = u.property_id AND f.frequency = 'one_time' AND f.required = 1
GROUP BY u.property_id, u.unit_type;

CREATE VIEW v_pet_costs AS
SELECT pp.property_id, p.name AS property, pp.cats_allowed, pp.dogs_allowed, pp.max_pets, pp.max_weight_lb,
       pp.breed_restrictions,
       COALESCE(SUM(CASE WHEN f.frequency = 'one_time' THEN f.amount END), 0) AS one_time_per_pet,
       COALESCE(SUM(CASE WHEN f.frequency = 'monthly' THEN f.amount END), 0) AS monthly_per_pet
FROM pet_policies pp JOIN properties p USING (property_id)
LEFT JOIN v_current_fees f ON f.property_id = pp.property_id AND f.category = 'pet'
GROUP BY pp.property_id;
"""

# CSV column -> table column subsets (CSVs carry extra fields that are not needed here)
TABLES = {
    "companies": ["company_id", "name", "ticker", "hq_city", "website", "description", "emergency_line",
                  "office_email", "source_urls", "verified_on"],
    "properties": ["property_id", "company_id", "name", "city", "state", "district", "address", "owner",
                   "year_built", "units", "floors", "has_elevator", "heat_controlled_by", "quiet_hours",
                   "office_hours", "site_contact", "site_phone", "emergency_line", "rent_regulated", "verified_on"],
    "unit_types": None, "fees": None, "pet_policies": None, "parking": None, "utilities": None, "amenities": None,
    "units": ["unit_id", "property_id", "unit_number", "floor", "unit_type", "bedrooms", "bathrooms", "sqft", "status"],
    "leases": ["lease_id", "unit_id", "tenant_id", "start_date", "end_date", "monthly_rent", "security_deposit",
               "lease_type", "pet_addendum"],
}


def _convert(value: str):
    if value == "":
        return None
    if value in ("True", "False"):
        return int(value == "True")
    return value


def build(db_path: Path = DB_PATH, as_of: str | None = None) -> dict[str, int]:
    DB_DIR.mkdir(parents=True, exist_ok=True)
    db_path.unlink(missing_ok=True)
    con = sqlite3.connect(db_path)
    con.executescript(SCHEMA)
    counts = {}
    for table, cols in TABLES.items():
        with (SRC / f"{table}.csv").open() as f:
            rows = list(csv.DictReader(f))
        cols = cols or list(rows[0].keys())
        con.executemany(f"INSERT INTO {table} ({', '.join(cols)}) VALUES ({', '.join('?' * len(cols))})",
                        [[_convert(r.get(c, "")) for c in cols] for r in rows])
        counts[table] = len(rows)
    con.executemany("INSERT INTO meta VALUES (?, ?)", [
        ("as_of", as_of or datetime.now(timezone.utc).date().isoformat()),
        ("built_at", datetime.now(timezone.utc).isoformat(timespec="seconds")),
    ])
    con.commit()
    problems = con.execute("PRAGMA foreign_key_check").fetchall()
    con.close()
    if problems:
        raise ValueError(f"foreign key violations: {problems[:5]}")
    return counts


def main() -> None:
    for table, n in build().items():
        print(f"{table:13s} {n:5d} rows")
    print(f"-> {DB_PATH.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
